#Você tem 15 poções para dividir igualmente entre 3 jogadores. Use o operador / para mostrar quantas poções cada um recebe.

pocao = 15
jogadores = 3

print(f"Há um total de {jogadores} jogadores, e {pocao}, poções.")

pocao2 = pocao / jogadores

print(f"Fica um total de {pocao2} para cada jogador.")
